import assert from "node:assert/strict";
import fs from "node:fs";
import { execFileSync } from "node:child_process";
import { chromium } from "/home/leo/.npm/_npx/e41f203b7505f1fb/node_modules/playwright/index.mjs";

const root = "/home/leo/projects/video-manage";
const out = root + "/.run/notification-validation";
const base = "http://127.0.0.1:18425";
const results = [];
const errors = [];
const fixture = JSON.parse(fs.readFileSync(out + "/fixtures.json"));
const db = (value) => Number(execFileSync("python3", [root + "/scripts/notification-fixture.py", JSON.stringify(value)], { encoding: "utf8" }).trim());
const check = (name, condition = true) => { assert.ok(condition, name); results.push(name); console.log("PASS", name); };
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", headless: true, args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, reducedMotion: "reduce" });
const page = await context.newPage();
page.on("pageerror", (e) => errors.push(e.message));
const toast = (id) => page.locator(`.task-toast[data-task-id="${id}"]`);
const waitToast = (id) => toast(id).waitFor({ state: "visible", timeout: 15000 });
const baseline = async (p = page) => {
  await p.waitForFunction(() => { try { return JSON.parse(sessionStorage.getItem("frame-archive:task-notifications:v1"))?.cursor !== undefined; } catch { return false; } });
};
const idle = (ms = 2300) => new Promise(resolve => setTimeout(resolve, ms));
try {
  // Fixture supports repeated runs.
  db({ id: fixture.old, state: "running", result: null });
  await page.goto(base);
  await baseline();
  await idle();
  check("历史已完成任务不弹出", await page.locator(".task-toast").count() === 0);
  check("超过最近 100 条的运行任务仍被跟踪", await page.evaluate((id) => JSON.parse(sessionStorage.getItem("frame-archive:task-notifications:v1")).pending.includes(id), fixture.old));
  await page.getByRole("link", { name: "搜索视频", exact: true }).focus();
  const before = await page.evaluate(() => ({ y: scrollY, focus: document.activeElement?.getAttribute("aria-label") }));
  db({ id: fixture.old, state: "done", result: { scanned: 8, created: 3 } });
  await waitToast(fixture.old);
  check("运行完成显示扫描结果", (await toast(fixture.old).innerText()).includes("新增 3 个视频"));
  const after = await page.evaluate(() => ({ y: scrollY, focus: document.activeElement?.getAttribute("aria-label") }));
  check("弹出不抢焦点、不移动页面", JSON.stringify(before) === JSON.stringify(after));
  const rect = await toast(fixture.old).boundingBox();
  check("通知固定在桌面右下角", rect.x > 1000 && rect.y > 650 && rect.x + rect.width < 1440 && rect.y + rect.height < 960);
  await page.screenshot({ path: out + "/desktop-notification.png" });
  await page.addScriptTag({ path: root + "/.run/design-audit/tooling/node_modules/axe-core/axe.min.js" });
  const axe = await page.evaluate(async () => (await axe.run(".task-notifications", { runOnly: { type: "tag", values: ["wcag2a","wcag2aa","wcag21aa"] } })).violations);
  fs.writeFileSync(out + "/axe.json", JSON.stringify(axe, null, 2));
  check("通知区域无 WCAG A/AA 违规", axe.length === 0);
  await toast(fixture.old).getByRole("link", { name: "查看任务" }).click();
  await page.locator(".job-notification-detail .job-card").waitFor();
  check("查看入口定位到旧任务详情", (await page.locator(".job-notification-detail").innerText()).includes("新增影像 3"));
  check("查看后通知关闭", await toast(fixture.old).count() === 0);
  await page.getByRole("link", { name: "全部影像", exact: true }).click();
  await idle();
  check("页面切换不重复通知", await page.locator(".task-toast").count() === 0);

  const quick = db({ kind: "subtitle_model_download", state: "done" });
  const failed = db({ kind: "subtitle_generate", state: "error", error: "音轨读取失败，请检查来源文件。" });
  const canceled = db({ state: "canceled" });
  const active = db({ kind: "subtitle_translate", state: "running" });
  await waitToast(quick); await waitToast(failed);
  check("两次轮询间直接完成的任务不会遗漏", (await toast(quick).innerText()).includes("模型已下载"));
  check("失败任务显示原因", (await toast(failed).innerText()).includes("音轨读取失败"));
  check("排队或取消不显示完成通知", await toast(canceled).count() === 0 && await toast(active).count() === 0);
  await toast(failed).getByRole("button").click();
  check("通知可单独关闭", await toast(failed).count() === 0 && await toast(quick).count() === 1);
  await page.getByRole("link", { name: "存储源", exact: true }).click();
  check("跨页面仍保留现有通知", await toast(quick).isVisible());
  await page.reload(); await baseline(); await idle();
  check("刷新不重播已经通知的结果", await page.locator(".task-toast").count() === 0);
  db({ id: active, state: "done" });
  await waitToast(active);
  check("刷新后继续跟踪未完成任务", (await toast(active).innerText()).includes("翻译字幕已完成"));
  await toast(active).getByRole("button").click();

  await page.route("**/api/jobs/notifications", route => route.abort("connectionfailed"));
  await idle();
  const recovered = db({ kind: "subtitle_generate", state: "done" });
  await idle();
  check("断网期间不显示虚假完成", await toast(recovered).count() === 0);
  await page.unroute("**/api/jobs/notifications");
  await page.evaluate(() => window.dispatchEvent(new Event("online")));
  await waitToast(recovered);
  check("连接恢复补发遗漏任务", await toast(recovered).isVisible());
  await toast(recovered).getByRole("button").click();

  await page.goto(base + "/videos/" + fixture.video);
  await page.locator("video").waitFor();
  await page.locator("video").evaluate(async v => { v.muted = true; await v.play(); });
  const response = await page.request.post(base + "/api/videos/" + fixture.video + "/convert", { data: { format: "mkv", subtitle_mode: "none", replace_source: false } });
  assert.equal(response.status(), 202, await response.text());
  const conversion = await response.json();
  await waitToast(conversion.id);
  check("真实格式转换任务完成后通知", (await toast(conversion.id).innerText()).includes("格式转换已完成"));
  check("转换结果可下载提示正确", (await toast(conversion.id).innerText()).includes("可以下载了"));
  check("通知不会暂停视频", await page.locator("video").evaluate(v => !v.paused && v.currentTime > 0));
  await toast(conversion.id).getByRole("link").click();
  const download = page.locator(".job-notification-detail").getByRole("link", { name: "下载文件" });
  await download.waitFor();
  const output = await page.request.get(base + await download.getAttribute("href"));
  check("任务详情中的真实转换文件可下载", output.status() === 200 && (await output.body()).length > 1000);

  await page.getByRole("link", { name: "全部影像", exact: true }).click();
  const hoverId = db({ kind: "subtitle_translate" });
  await waitToast(hoverId);
  await toast(hoverId).hover();
  await idle(11000);
  check("悬停超过自动关闭时间仍保留", await toast(hoverId).isVisible());
  await page.mouse.move(20, 20);
  await toast(hoverId).waitFor({ state: "detached", timeout: 12000 });
  check("离开悬停后自动关闭", await toast(hoverId).count() === 0);
  const focused = db({ kind: "subtitle_generate" });
  await waitToast(focused);
  await toast(focused).getByRole("button").focus();
  await idle(11000);
  check("键盘聚焦时暂停自动关闭", await toast(focused).isVisible());
  await page.keyboard.press("Enter");
  check("键盘可关闭通知", await toast(focused).count() === 0);
  const auto = db({ kind: "subtitle_model_download" });
  await waitToast(auto);
  await toast(auto).waitFor({ state: "detached", timeout: 12000 });
  check("关闭聚焦通知后不会卡住后续自动关闭", await toast(auto).count() === 0);

  const burst = Array.from({ length: 5 }, (_, i) => db({ kind: i % 2 ? "subtitle_translate" : "subtitle_generate" }));
  await waitToast(burst[0]);
  await page.waitForFunction(() => document.querySelector(".task-toast-summary")?.textContent.includes("2 条"));
  check("多个任务同时完成最多显示三张卡片", await page.locator(".task-toast").count() === 3);
  await toast(burst[0]).getByRole("button").click();
  await waitToast(burst[3]);
  check("关闭后按顺序展示后续通知", await page.locator(".task-toast").count() === 3);
  await page.getByRole("button", { name: "关闭全部任务通知" }).click();
  check("可以关闭整组通知", await page.locator(".task-toast").count() === 0);

  await page.setViewportSize({ width: 390, height: 844 });
  const phone = db({ kind: "convert_format", state: "error", error: "当前视频音轨无法转换，请查看任务详情后重试。" });
  await waitToast(phone);
  await page.screenshot({ path: out + "/mobile-notification.png" });
  const mobileRect = await toast(phone).boundingBox();
  check("手机通知保持右下角且完整显示", mobileRect.x >= 0 && mobileRect.x + mobileRect.width <= 390 && mobileRect.y + mobileRect.height <= 844);
  check("手机无横向溢出", await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await toast(phone).getByRole("button").click();
  await page.setViewportSize({ width: 320, height: 640 });
  const small = db({ kind: "subtitle_translate" });
  await waitToast(small);
  check("320px 窄屏正常显示", await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await toast(small).getByRole("button").click();

  const blocked = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  await blocked.addInitScript(() => { Object.defineProperty(window, "sessionStorage", { get() { throw new DOMException("Blocked"); } }); });
  const p2 = await blocked.newPage();
  p2.on("pageerror", e => errors.push(e.message));
  await p2.goto(base);
  await p2.waitForResponse(r => r.url().endsWith("/api/jobs/notifications") && r.status() === 200);
  const noStorage = db({ kind: "subtitle_model_download" });
  await p2.locator(`[data-task-id="${noStorage}"]`).waitFor();
  check("浏览器禁用存储仍可通知", await p2.locator(".task-toast").count() === 1);
  await blocked.close();
  check("浏览器无未捕获异常", errors.length === 0);
  fs.writeFileSync(out + "/browser-results.json", JSON.stringify({ count: results.length, results, errors }, null, 2));
} finally {
  await browser.close();
}
