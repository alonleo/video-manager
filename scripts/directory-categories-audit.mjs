// Real browser, real API and real filesystem through an isolated audit server.
import assert from "node:assert/strict";
import { readFile, writeFile, access } from "node:fs/promises";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const marker = JSON.parse(await readFile(".run/directory-audit-latest.json", "utf8"));
const base = `http://127.0.0.1:${marker.port}`;
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || "/usr/bin/google-chrome" });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const errors = [];
page.on("pageerror", e => errors.push(e.message));
const checks = [];
const pass = (name) => { checks.push(name); console.log("PASS", name); };
try {
  await page.goto(base);
  await page.getByRole("combobox", { name: "目录分类" }).selectOption("1:旅行");
  await page.getByRole("heading", { name: "海边影像", exact: true }).waitFor();
  assert.match(page.url(), /category=/);
  await page.reload();
  assert.equal(await page.getByRole("combobox", { name: "目录分类" }).inputValue(), "1:旅行");
  pass("父目录分类筛选与URL持久化");
  await page.getByRole("button", { name: "新建分类", exact: true }).click();
  const create = page.getByRole("dialog", { name: "新建分类", exact: true });
  await create.getByLabel("创建位置").selectOption("1:");
  await create.getByLabel("分类名称").fill("珍藏");
  await create.getByRole("button", { name: "创建目录", exact: true }).click();
  await create.waitFor({ state: "hidden" });
  await access(`${marker.root}/珍藏`);
  assert.equal(await page.getByRole("combobox", { name: "目录分类" }).inputValue(), "1:珍藏");
  pass("新建分类实际创建目录并选中空分类");
  await page.getByRole("button", { name: "新建分类", exact: true }).click();
  await create.getByLabel("创建位置").selectOption("1:");
  await create.getByLabel("分类名称").fill("珍藏");
  await create.getByRole("button", { name: "创建目录", exact: true }).click();
  await create.getByRole("alert").waitFor();
  assert.match(await create.getByRole("alert").textContent(), /同名/);
  await page.keyboard.press("Escape");
  await create.waitFor({ state: "hidden" });
  pass("同名目录冲突提示与Escape关闭");
  await page.getByRole("combobox", { name: "目录分类" }).selectOption("1:旅行");
  await page.getByRole("heading", { name: "海边影像", exact: true }).click();
  await page.getByRole("button", { name: "移动视频", exact: true }).click();
  const move = page.getByRole("dialog", { name: "移动视频", exact: true });
  await move.getByLabel("目标分类").selectOption("1:珍藏");
  await page.screenshot({ path: `${marker.work}/move-dialog-desktop.png`, fullPage: true });
  await move.getByRole("button", { name: "确认移动文件", exact: true }).click();
  await move.waitFor({ state: "hidden" });
  await access(`${marker.root}/珍藏/海边.mp4`);
  await assert.rejects(access(`${marker.root}/旅行/海边.mp4`));
  const detail = await (await page.request.get(`${base}/api/videos/1`)).json();
  assert.equal(detail.categories[0].name, "珍藏");
  assert.equal(detail.is_favorite, true);
  assert.equal(detail.sources[0].uri, "local:珍藏/海边.mp4");
  pass("视频真实移动、来源引用和分类自动更新");
  const stream = await page.request.get(`${base}/api/videos/1/stream`, { headers: { Range: "bytes=0-63" } });
  assert.equal(stream.status(), 206);
  assert.equal((await stream.body()).length, 64);
  pass("移动后的原始视频Range播放");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}/?category=1%3A%E7%8F%8D%E8%97%8F`);
  await page.getByRole("heading", { name: "海边影像", exact: true }).waitFor();
  await page.getByRole("button", { name: "新建分类", exact: true }).click();
  await create.waitFor();
  await page.screenshot({ path: `${marker.work}/create-dialog-mobile.png`, fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.keyboard.press("Escape");
  pass("390px移动端弹窗和筛选无横向溢出");
  assert.deepEqual(errors, []);
  pass("浏览器无未捕获异常");
  await writeFile(`${marker.work}/results.json`, JSON.stringify({ checks, errors }, null, 2));
} finally {
  await browser.close();
}
