import path from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const base = process.env.WASM_AUDIT_URL || 'http://127.0.0.1:8427';
const root = path.resolve(import.meta.dirname, '..');
const browser = await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || '/usr/bin/google-chrome',args:['--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const checks = [], errors=[];
page.on('pageerror',e=>errors.push(e.message));
const pass=name=>{checks.push(name);console.log('PASS',name);};
const playerState = async () => page.evaluate(async()=>{
  const {default:P}=await import('/player-engine/libmedia-1.3.1/avplayer.js');
  const p=P.Instances.at(-1);
  return {time:Number(p.currentTime),rate:p.getPlaybackRate(),volume:p.getVolume(),
    count:P.Instances.length,status:p.getStatus(),audio:P.audioContext.state,video:p.hasVideo()};
});
try {
  await fetch(base+'/api/videos/6/progress',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({position_ms:0,finished:false})});
  await page.goto(base+'/videos/6');
  await page.getByRole('button',{name:'开始播放',exact:true}).click();
  await page.getByRole('button',{name:'暂停',exact:true}).waitFor();
  await page.waitForTimeout(1500);
  assert.equal((await playerState()).audio,'running');pass('AudioContext running with user gesture');
  await page.getByRole('button',{name:'暂停',exact:true}).click();
  await page.getByRole('button',{name:'播放',exact:true}).waitFor();
  await page.waitForTimeout(750); // worker clock reports arrive asynchronously
  assert.equal((await playerState()).status,8);
  const paused=(await playerState()).time;
  await page.waitForTimeout(400);
  assert.ok(Math.abs((await playerState()).time-paused)<120);pass('Pause stops playback clock');
  await page.getByRole('button',{name:'倍速',exact:true}).click();
  await page.getByRole('button',{name:'1.5×',exact:true}).click();
  assert.equal((await playerState()).rate,1.5);pass('Speed controls independent engine');
  await page.getByRole('button',{name:'音量设置',exact:true}).click();
  await page.getByRole('button',{name:'静音',exact:true}).click();
  assert.equal((await playerState()).volume,0);
  await page.getByRole('button',{name:'取消静音',exact:true}).click();
  assert.ok((await playerState()).volume>0);pass('Mute and volume restore');
  await page.getByRole('button',{name:'字幕',exact:true}).click();
  await page.getByRole('button',{name:/中文.*中文测试/}).click();
  await page.locator('.wasm-captions').filter({hasText:'独立解码字幕测试'}).waitFor();
  await page.getByRole('switch',{name:'显示字幕'}).click();
  assert.equal(await page.locator('.wasm-captions').count(),0);
  await page.getByRole('switch',{name:'显示字幕'}).click();
  await page.getByRole('button',{name:/English.*English test/}).click();
  await page.locator('.wasm-captions').filter({hasText:'Independent decoder captions'}).waitFor();
  await page.getByRole('button',{name:'大',exact:true}).click();
  assert.equal(await page.locator('.wasm-captions.caption-large').count(),1);pass('Subtitle visibility, language, and size');
  await page.getByRole('button',{name:'字幕',exact:true}).click();
  await page.getByRole('button',{name:'全屏',exact:true}).click();
  assert.equal(await page.evaluate(()=>document.fullscreenElement?.classList.contains('player-stage')),true);
  await page.getByRole('button',{name:'退出全屏',exact:true}).click();pass('Fullscreen stage');
  const seekFrom=Number(await page.getByRole('slider',{name:'播放进度'}).inputValue())*1000;
  await page.getByRole('region',{name:/视频播放区域/}).focus();
  await page.keyboard.press('ArrowRight');
  await page.waitForTimeout(1000);
  const history=await(await fetch(base+'/api/videos/6/progress')).json();
  assert.ok(history.position_ms>=seekFrom+4800,JSON.stringify({history,seekFrom,engine:await playerState()}));pass('Keyboard seek saves confirmed progress');
  await page.reload();
  await page.getByRole('button',{name:'开始播放',exact:true}).waitFor();
  const slider=page.getByRole('slider',{name:'播放进度'});
  assert.ok(Number(await slider.inputValue())*1000>=history.position_ms-150);pass('Reload restores position');
  await page.getByRole('button',{name:'开始播放',exact:true}).click();
  await page.getByRole('button',{name:'暂停',exact:true}).waitFor();
  await page.waitForTimeout(300);
  assert.ok((await playerState()).time>=history.position_ms-250);pass('Resume decodes at saved position');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));pass('Mobile layout fits viewport');
  await page.screenshot({path:root+'/.run/wasm-validation/mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('link',{name:/全部影像/}).click();
  await page.waitForTimeout(600);
  assert.equal(await page.evaluate(async()=>{const {default:P}=await import('/player-engine/libmedia-1.3.1/avplayer.js');return P.Instances.length;}),0);
  await page.locator('a[href="/videos/18"]').first().click();
  await page.getByRole('button',{name:'开始播放',exact:true}).waitFor();
  assert.equal((await playerState()).count,1);pass('Navigation disposes old player');
  assert.deepEqual(errors,[]);pass('No uncaught browser errors');
} catch(error) { console.error(error); errors.push(error.message); process.exitCode=1; }
finally { await writeFile(root+'/.run/wasm-validation/controls.json',JSON.stringify({checks,errors},null,2)); await browser.close(); }
