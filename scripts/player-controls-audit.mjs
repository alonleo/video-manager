// Run against the disposable subtitle-audit-server.py fixture, never the real library.
import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.AUDIT_URL || 'http://127.0.0.1:8423';
const out = '.run/player-controls-validation';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [], checks = [];
page.on('pageerror', e => errors.push(e.message));
const pass = message => { checks.push(message); console.log('PASS', message); };
const captions = () => page.getByRole('region', { name: '字幕菜单', exact: true });
const openCaptions = async () => {
  const button = page.getByRole('button', { name: '字幕', exact: true });
  if (await button.getAttribute('aria-expanded') !== 'true') await button.click();
};
const closeMenu = () => page.keyboard.press('Escape');
const waitCue = text => page.waitForFunction(text => document.querySelector('video')?.textTracks[0]?.cues?.[0]?.text.includes(text), text);
try {
  const fixture = await (await page.request.get(base + '/api/videos/1')).json();
  assert.equal(fixture.title, '字幕工作台 · 验证影像', 'Use only the isolated subtitle audit fixture');
  const previous = await (await page.request.get(base + '/api/videos/1/subtitles')).json();
  for (const t of previous) assert.ok((await page.request.delete(base + '/api/subtitles/' + t.id)).ok());
  await page.goto(base + '/settings');
  await page.getByRole('heading', { name: '管理视频字幕' }).waitFor();
  await page.getByRole('button', { name: '字幕工作台 · 验证影像' }).click();
  await page.getByRole('heading', { name: '字幕与翻译', exact: true }).waitFor();
  assert.ok(page.url().endsWith('?video=1'));
  pass('Settings navigation and video selection');
  await page.getByLabel('选择字幕文件').setInputFiles({ name: 'English.srt', mimeType: 'text/plain',
    buffer: Buffer.from('1\n00:00:00,000 --> 00:00:03,000\nHello subtitle world.\n\n2\n00:00:03,100 --> 00:00:07,000\nBilingual captions are ready.\n') });
  await page.waitForFunction(() => document.querySelector('.subtitle-display-row select')?.selectedOptions[0]?.textContent.includes('English.srt'));
  pass('Subtitle import lives in settings');
  await page.getByRole('button', { name: '翻译字幕', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.subtitle-display-row select')?.selectedOptions[0]?.textContent.includes('zh-CN'), null, { timeout: 30000 });
  pass('Translation creates a separate language track');
  await page.getByLabel('导出内容').selectOption('bilingual');
  for (const format of ['SRT', 'VTT']) {
    const href = await page.getByRole('link', { name: '导出 ' + format, exact: true }).getAttribute('href');
    const exported = await page.request.get(new URL(href, base).href);
    const text = await exported.text();
    assert.ok(exported.ok() && text.includes('你好') && text.includes('Hello'));
  }
  pass('Bilingual SRT and VTT export from settings');
  await page.screenshot({ path: out + '/settings-desktop.png', fullPage: true });
  await page.getByRole('link', { name: '返回播放', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('video')?.readyState >= 2);
  assert.equal(await page.locator('video').evaluate(v => v.controls), false);
  assert.equal(await page.getByRole('heading', { name: '字幕与翻译', exact: true }).count(), 0);
  pass('Native controls and subtitle workspace removed from playback page');
  await openCaptions();
  await captions().getByRole('button', { name: /English.srt/ }).click();
  await closeMenu();
  await waitCue('Hello');
  await page.getByRole('button', { name: '播放', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('video').paused && document.querySelector('video').currentTime > 0);
  await page.getByRole('button', { name: '暂停', exact: true }).click();
  assert.equal(await page.locator('video').evaluate(v => v.paused), true);
  pass('Custom play and pause');
  await page.locator('video').evaluate(v => { v.currentTime = 0; });
  await page.getByRole('button', { name: '播放', exact: true }).click();
  const videoBounds = await page.locator('video').boundingBox();
  await page.mouse.move(videoBounds.x + 30, videoBounds.y + 30);
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.custom-player-controls')).opacity === '0', null, { timeout: 5000 });
  await page.mouse.move(videoBounds.x + 40, videoBounds.y + 40);
  await page.getByRole('button', { name: '暂停', exact: true }).click();
  pass('Controls auto-hide during playback and reappear on pointer movement');
  await page.getByRole('slider', { name: '播放进度' }).fill('1.5');
  await page.waitForFunction(() => Math.abs(document.querySelector('video').currentTime - 1.5) < .15);
  await page.getByRole('button', { name: '倍速', exact: true }).click();
  await page.getByRole('button', { name: '1.5×', exact: true }).click();
  assert.equal(await page.locator('video').evaluate(v => v.playbackRate), 1.5);
  await page.getByRole('button', { name: '音量设置', exact: true }).click();
  await page.getByRole('slider', { name: '音量', exact: true }).fill('0.35');
  assert.equal(await page.locator('video').evaluate(v => v.volume), .35);
  await page.getByRole('button', { name: '静音', exact: true }).click();
  assert.equal(await page.locator('video').evaluate(v => v.muted), true);
  await closeMenu();
  pass('Seek, speed, volume and mute controls');
  await openCaptions();
  await captions().getByRole('button', { name: /简体中文/ }).click();
  await waitCue('你好');
  assert.ok(Math.abs(await page.locator('video').evaluate(v => v.currentTime) - 1.5) < .2);
  await captions().getByRole('switch', { name: '原文 + 译文' }).click();
  await waitCue('Hello');
  assert.ok((await page.locator('video').evaluate(v => v.textTracks[0].cues[0].text)).includes('你好'));
  await captions().getByRole('button', { name: '大', exact: true }).click();
  assert.ok((await page.locator('video').getAttribute('class')).includes('video-caption-large'));
  pass('Subtitle language, bilingual mode and font size without restarting video');
  await captions().getByRole('switch', { name: '显示字幕' }).click();
  assert.equal(await page.locator('video track').count(), 0);
  await page.reload();
  await page.waitForFunction(() => document.querySelector('video')?.readyState >= 2);
  await openCaptions();
  assert.equal(await captions().getByRole('switch', { name: '显示字幕' }).getAttribute('aria-checked'), 'false');
  assert.equal(await page.locator('video track').count(), 0);
  await captions().getByRole('switch', { name: '显示字幕' }).click();
  await waitCue('你好');
  assert.equal(await captions().getByRole('button', { name: '大', exact: true }).getAttribute('aria-pressed'), 'true');
  pass('Subtitle off, language selection and size survive refresh');
  await closeMenu();
  const stage = page.getByRole('region', { name: /^视频播放区域/ });
  await stage.focus();
  await page.keyboard.press('m');
  assert.equal(await page.locator('video').evaluate(v => v.muted), true);
  await page.keyboard.press('ArrowRight');
  assert.ok(await page.locator('video').evaluate(v => v.currentTime) >= 5);
  await page.keyboard.press('ArrowLeft');
  await page.getByRole('button', { name: '全屏', exact: true }).click();
  await page.waitForFunction(() => document.fullscreenElement?.classList.contains('player-stage'));
  await openCaptions();
  assert.equal(await captions().isVisible(), true);
  await page.locator('video').evaluate(v => { v.currentTime = 1; });
  await page.waitForFunction(() => document.querySelector('video')?.textTracks[0]?.activeCues?.length > 0);
  assert.equal(await page.locator('video').evaluate(v => v.textTracks[0].mode), 'showing');
  await page.screenshot({ path: out + '/fullscreen-captions.png' });
  await closeMenu();
  await page.getByRole('button', { name: '退出全屏', exact: true }).click();
  pass('Keyboard controls and fullscreen keep custom controls and captions');
  await openCaptions();
  await page.screenshot({ path: out + '/player-desktop.png', fullPage: true });
  const axe = await readFile('.run/design-audit/tooling/node_modules/axe-core/axe.min.js', 'utf8');
  await page.addScriptTag({ content: axe });
  const a11y = await page.evaluate(async () => (await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa'] } })).violations.map(v => ({ id: v.id, impact: v.impact, nodes: v.nodes.map(n => n.target) })));
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.screenshot({ path: out + '/player-mobile-' + width + '.png', fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    const bounds = await captions().boundingBox(), parent = await stage.boundingBox();
    assert.ok(bounds.x >= parent.x && bounds.x + bounds.width <= parent.x + parent.width + 1);
    assert.ok(bounds.y >= parent.y);
    await captions().getByRole('switch', { name: '显示字幕' }).click();
    assert.equal(await page.locator('video track').count(), 0);
    await captions().getByRole('switch', { name: '显示字幕' }).click();
  }
  pass('390px and 320px player menus fit and remain usable');
  await page.getByRole('link', { name: '字幕与翻译设置', exact: true }).click();
  assert.ok(page.url().includes('/settings?video=1'));
  await page.getByRole('heading', { name: '字幕与翻译', exact: true }).waitFor();
  await page.screenshot({ path: out + '/settings-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.getByRole('link', { name: 'AI 模型与服务', exact: true }).click();
  await page.getByRole('button', { name: '保存 AI 设置' }).waitFor();
  assert.equal((await page.content()).includes('audit-only-not-a-real-key'), false);
  await page.getByRole('button', { name: '检测翻译 API', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '连接成功' }).waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  pass('Per-video settings link, mobile settings and existing AI service test');
  await page.getByRole('link', { name: '字幕与翻译', exact: true }).click();
  await page.getByRole('button', { name: '生成字幕', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.subtitle-display-row select')?.selectedOptions[0]?.textContent.includes('原文 · audit-whisper'), null, { timeout: 30000 });
  await page.getByRole('button', { name: '校对字幕', exact: true }).click();
  await page.getByLabel('第 1 条字幕', { exact: true }).fill('Edited caption from settings.');
  await page.getByRole('button', { name: '保存校对', exact: true }).click();
  await page.getByRole('link', { name: '返回播放', exact: true }).click();
  await openCaptions();
  await captions().getByRole('button', { name: /English.*原文/ }).click();
  await waitCue('Edited caption');
  pass('Generation and editing remain functional after migration');
  await page.setViewportSize({ width: 1440, height: 1100 });
  // Deleting the selected track elsewhere must not leave stale captions.
  const tracks = await (await page.request.get(base + '/api/videos/1/subtitles')).json();
  for (const t of tracks) assert.ok((await page.request.delete(base + '/api/subtitles/' + t.id)).ok());
  await page.waitForFunction(() => !document.querySelector('video track'), null, { timeout: 15000 });
  await captions().getByText('暂无字幕，前往设置导入或生成。').waitFor();
  pass('Track deletion refreshes playback and empty state');
  assert.deepEqual(errors, []);
  await writeFile(out + '/results.json', JSON.stringify({ checks, errors, a11y }, null, 2));
  console.log(JSON.stringify({ checks: checks.length, errors, a11y }));
} catch (e) {
  await page.screenshot({ path: out + '/failure.png', fullPage: true });
  console.error(e);
  process.exitCode = 1;
} finally { await browser.close(); }
