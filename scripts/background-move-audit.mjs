import assert from "node:assert/strict";
import fs from "node:fs";
import crypto from "node:crypto";
import { chromium } from "/home/leo/.npm/_npx/e41f203b7505f1fb/node_modules/playwright/index.mjs";
const root="/home/leo/projects/video-manage", out=root+"/.run/background-move-validation";
const base="http://127.0.0.1:18427", fixtures=JSON.parse(fs.readFileSync(out+"/fixtures.json"));
const checks=[], errors=[];
const check=(name,value=true)=>{assert.ok(value,name);checks.push(name);console.log("PASS",name);};
const hash=p=>crypto.createHash("sha256").update(fs.readFileSync(p)).digest("hex");
const browser=await chromium.launch({executablePath:"/usr/bin/google-chrome",headless:true,args:["--no-sandbox"]});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:"reduce"});
const page=await context.newPage();
page.on("pageerror",e=>errors.push(e.message));
let job, second;
try {
  const first=fixtures.videos[0], digest=hash(first.path);
  check("使用真实的跨文件系统目标",fs.statSync(first.path).dev!==fs.statSync(fixtures.target).dev);
  await page.goto(base+"/videos/"+first.video);
  await page.getByRole("button",{name:"移动视频",exact:true}).click();
  const dialog=page.getByRole("dialog",{name:"移动视频",exact:true});
  await dialog.waitFor();
  await dialog.getByRole("combobox",{name:"目标分类",exact:true}).selectOption(fixtures.target_storage+":归档");
  check("弹窗解释后台执行和完成通知",(await dialog.innerText()).includes("提交后可离开页面"));
  await page.screenshot({path:out+"/desktop-dialog.png"});
  await page.addScriptTag({path:root+"/.run/design-audit/tooling/node_modules/axe-core/axe.min.js"});
  const violations=await page.evaluate(async()=>(await axe.run("dialog[open]",{runOnly:{type:"tag",values:["wcag2a","wcag2aa","wcag21aa"]}})).violations);
  check("移动弹窗通过无障碍检查",violations.length===0);
  const responsePromise=page.waitForResponse(r=>r.url().endsWith("/api/videos/"+first.video+"/move")&&r.request().method()==="POST");
  const started=Date.now();
  await dialog.getByRole("button",{name:"提交后台移动",exact:true}).click();
  const response=await responsePromise;
  job=await response.json();
  check("提交返回202且不等待文件移动",response.status()===202&&Date.now()-started<3000&&fs.existsSync(first.path));
  await dialog.waitFor({state:"hidden"});
  await page.getByRole("link",{name:"查看任务 #"+job.id,exact:true}).click();
  await page.getByLabel("通知对应任务").getByRole("button",{name:"取消排队"}).waitFor();
  check("提交后可进入任务中心，排队状态可取消");
  await page.reload();
  await page.getByLabel("通知对应任务").getByRole("button",{name:"取消排队"}).waitFor();
  check("刷新后任务持续可见");
  // Submit another file while the shared library lock is held; cancel just that job.
  const api=context.request;
  const cancelFixture=fixtures.videos[1];
  const queued=await api.post(base+"/api/videos/"+cancelFixture.video+"/move",{data:{
    source_id:cancelFixture.source,storage_id:fixtures.target_storage,path:"归档"}});
  second=await queued.json();
  check("其他视频可继续加入队列",queued.status()===202&&second.id!==job.id);
  await page.goto(base+"/jobs?job="+second.id);
  await page.getByLabel("通知对应任务").getByRole("button",{name:"取消排队"}).click();
  await page.getByLabel("通知对应任务").getByText("已取消",{exact:true}).waitFor();
  check("可从任务中心取消尚未开始的移动",fs.existsSync(cancelFixture.path));
  // Close the original page entirely. Another already-open library page receives completion.
  const library=await context.newPage();
  library.on("pageerror",e=>errors.push(e.message));
  await library.goto(base+"/");
  await library.getByRole("combobox",{name:"目录分类"}).selectOption(fixtures.source_storage+":来源");
  await library.getByText("后台移动验证 1",{exact:true}).first().waitFor();
  await library.waitForFunction(()=>JSON.parse(sessionStorage.getItem("frame-archive:task-notifications:v1")||"null")?.pending?.length>0);
  await page.close();
  fs.writeFileSync(out+"/release","go");
  const toast=library.locator('[data-task-id="'+job.id+'"]');
  await toast.getByRole("heading",{name:"移动视频已完成",exact:true}).waitFor({timeout:30000});
  check("关闭原页面后仍完成，并在右下角弹出通知");
  const destination=fixtures.target+"/归档/"+first.path.split("/").at(-1);
  check("跨盘目标内容完整，原文件已清理",!fs.existsSync(first.path)&&hash(destination)===digest);
  await library.getByText("后台移动验证 1",{exact:true}).first().waitFor({state:"hidden"});
  check("通知自动刷新来源分类列表");
  await library.screenshot({path:out+"/completion-toast.png"});
  await toast.getByRole("link",{name:"查看任务"}).click();
  await library.getByLabel("通知对应任务").getByText("已完成",{exact:true}).waitFor();
  check("通知链接直达完成的移动任务");
  const result=await (await api.get(base+"/api/jobs/"+job.id)).json();
  check("任务显示已完成和100%进度",result.state==="done"&&result.progress===1&&result.result.category.name==="归档");
  await library.setViewportSize({width:390,height:844});
  await library.goto(base+"/videos/"+fixtures.videos[2].video);
  await library.getByRole("button",{name:"移动视频",exact:true}).click();
  const mobile=library.getByRole("dialog",{name:"移动视频",exact:true});
  await mobile.waitFor();
  check("手机弹窗无横向溢出",await mobile.evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  await library.screenshot({path:out+"/mobile-dialog.png"});
  await mobile.getByRole("button",{name:"取消",exact:true}).click();
  check("浏览器无脚本异常",errors.length===0);
  fs.writeFileSync(out+"/browser-results.json",JSON.stringify({checks,errors,result},null,2));
} catch(e) {
  fs.writeFileSync(out+"/browser-failure.json",JSON.stringify({checks,errors,error:String(e)},null,2));
  console.error(e);process.exitCode=1;
} finally {await browser.close();}
