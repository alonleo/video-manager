import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const marker = JSON.parse(await readFile(".run/conversion-subtitles-audit-latest.json", "utf8"));
const base = "http://127.0.0.1:" + marker.port;
const browser = await chromium.launch({headless: true, executablePath: process.env.CHROMIUM_PATH || "/usr/bin/google-chrome"});
const page = await browser.newPage({viewport: {width: 1440, height: 1050}});
const errors = [], checks = [];
page.on("pageerror", error => errors.push(error.message));
const pass = name => {checks.push(name); console.log("PASS", name);};
const hash = buffer => createHash("sha256").update(buffer).digest("hex");
const probe = path => JSON.parse(execFileSync("ffprobe", ["-v","error","-show_streams","-show_format","-of","json",path]));
try {
  const original = await readFile(marker.source);
  await page.goto(base + "/videos/1");
  const actions = page.getByRole("dialog", {name:"转换格式",exact:true});
  const controls = page.locator(".player-action-row");
  const results = page.getByRole("region", {name:"视频基本操作"});
  await controls.getByRole("button", {name:"转换格式",exact:true}).click();
  assert.equal(await actions.getByLabel("目标格式").inputValue(),"mkv");
  assert.equal(await actions.getByLabel("目标格式").locator("option").count(),6);
  assert.equal(await actions.getByRole("checkbox", {name:/转换成功后替换原视频/}).isChecked(), false);
  pass("六种格式可选，默认MKV且默认保留原片");
  await actions.getByLabel("字幕处理").selectOption("embed");
  await actions.getByRole("checkbox", {name:/中文字幕/}).check();
  await actions.getByRole("checkbox", {name:/英文字幕/}).check();
  const submitted = page.waitForResponse(r=>r.url().endsWith("/api/videos/1/convert") && r.request().method()==="POST");
  await actions.getByRole("button", {name:"开始转换",exact:true}).click();
  const first = await (await submitted).json();
  await results.locator("article").filter({hasText:"格式转换 #"+first.id}).getByRole("link",{name:"下载文件"}).waitFor({timeout:30000});
  const result1 = await (await page.request.get(base+"/api/jobs/"+first.id)).json();
  assert.equal(result1.state,"done");
  const output1 = marker.work+"/outputs/exports/job-"+first.id+"/result.mkv";
  assert.equal(probe(output1).streams.filter(s=>s.codec_type==="subtitle").length,2);
  assert.equal(hash(await readFile(marker.source)),hash(original));
  pass("界面通过真实队列生成双字幕轨MKV，原片字节不变");
  await controls.getByRole("button", {name:"转换格式",exact:true}).click();
  await actions.getByLabel("目标格式").selectOption("avi");
  await actions.getByLabel("字幕处理").selectOption("embed");
  assert.equal(await actions.getByRole("checkbox", {name:/中文字幕/}).isDisabled(),true);
  await actions.getByLabel("字幕处理").selectOption("burn");
  await actions.getByRole("checkbox", {name:/中文字幕/}).check();
  await actions.getByLabel("目标格式").selectOption("m2ts");
  await actions.getByRole("checkbox", {name:/转换成功后替换原视频/}).check();
  pass("不兼容文字软字幕被禁用，烧录和替换可显式选择");
  await actions.scrollIntoViewIfNeeded();
  await actions.screenshot({path:marker.work+"/conversion-desktop.png"});
  await page.setViewportSize({width:390,height:844});
  await actions.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await actions.screenshot({path:marker.work+"/conversion-mobile.png"});
  pass("390px转换选项布局无横向溢出");
  const replaced = page.waitForResponse(r=>r.url().endsWith("/api/videos/1/convert") && r.request().method()==="POST");
  await actions.getByRole("button",{name:"转换并替换原视频",exact:true}).click();
  const second = await (await replaced).json();
  const record = results.locator("article").filter({hasText:"格式转换 #"+second.id});
  await record.getByText("已替换原视频 · 原片备份位置",{exact:true}).waitFor({timeout:30000});
  const result2 = (await (await page.request.get(base+"/api/jobs/"+second.id)).json()).result;
  assert.equal(result2.replaced,true);
  assert.equal(hash(await readFile(result2.backup_path)),hash(original));
  await assert.rejects(readFile(marker.source));
  const output2 = marker.source.replace(/\.mp4$/,".m2ts");
  const raw = probe(output2);
  assert.equal(raw.streams.some(s=>s.codec_type==="subtitle"),false);
  assert.equal(raw.streams.find(s=>s.codec_type==="video").codec_name,"h264");
  const bytes = await readFile(output2);
  assert.equal(bytes[4],0x47);assert.equal(bytes[196],0x47);
  execFileSync("ffmpeg",["-v","error","-i",output2,"-ss","1","-frames:v","1",marker.work+"/burned-frame.png"]);
  pass("真实M2TS烧录并替换，原片备份逐字节一致");
  const video = await (await page.request.get(base+"/api/videos/1")).json();
  assert.equal(video.sources[0].local_path,output2);
  const stream = await page.request.get(base+"/api/videos/1/stream",{headers:{Range:"bytes=0-99"}});
  assert.equal(stream.status(),206);
  assert.deepEqual(errors,[]);
  pass("替换后引用和播放接口正常，无浏览器异常");
  await writeFile(marker.work+"/results.json",JSON.stringify({checks,errors},null,2));
} finally {await browser.close();}
